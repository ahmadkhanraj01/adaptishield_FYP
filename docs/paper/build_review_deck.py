def slide(bg=PAPER):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = bg
    return s


def text(s, x, y, w, h, runs, align=PP_ALIGN.LEFT, spacing=None, anchor=None,
         line_spacing=1.22):
    tb = s.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    if anchor:
        tf.vertical_anchor = anchor
    paras = runs if isinstance(runs[0], list) else [runs]
    for i, para in enumerate(paras):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        if spacing:
            p.space_after = Pt(spacing)
        for t, size, color, bold, font in para:
            r = p.add_run()
            r.text = t
            r.font.size = Pt(size)
            r.font.color.rgb = color
            r.font.bold = bold
            r.font.name = font
        p.line_spacing = line_spacing
    return tb


def rect(s, x, y, w, h, fill, line=None, radius=None):
    shape = s.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE, x, y, w, h)
    if radius:
        shape.adjustments[0] = radius
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill
    if line:
        shape.line.color.rgb = line
        shape.line.width = Pt(0.75)
    else:
        shape.line.fill.background()
    shape.shadow.inherit = False
    return shape


def eyebrow(s, label, color=MUTED, y=Inches(0.55)):
    text(s, M, y, CW, Inches(0.3), [(label.upper(), 10.5, color, True, MONO)])


def heading(s, title, y=Inches(0.95), size=32, color=INK):
    text(s, M, y, CW, Inches(0.9), [(title, size, color, True, SERIF)])


def sub(s, line, y=Inches(1.62), size=14, color=MUTED, w=None):
    text(s, M, y, w or CW, Inches(0.4), [(line, size, color, False, SANS)])


def footer(s, note=""):
    _n[0] += 1
    text(s, M, H - Inches(0.55), CW, Inches(0.3),
         [(f"ADAPTISHIELD  ·  {_n[0]:02d}" + (f"  ·  {note}" if note else ""),
           8.5, MUTED, False, MONO)])


def divider(kicker, title, blurb):
    s = slide(INK)
    text(s, M, Inches(2.5), CW, Inches(0.4),
         [(kicker.upper(), 12, PALE, True, MONO)])
