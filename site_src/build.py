def _load(rel):
    with open(os.path.join(REPO, rel)) as fh:
        return json.load(fh)


# ── figures ──────────────────────────────────────────────────────────────
def figures():
    """Regenerate from results/ when the toolchain is present, then copy."""
    # Opt-in: matplotlib re-stamps the PDFs on every run and dirties the tree.
    # The committed figures ARE generated from results/ — make_figures.py is
    # the only thing that writes them — so copying them keeps the guarantee.
    if os.environ.get("SITE_REGEN_FIGURES"):
        subprocess.run(["python3", "paper/make_figures.py"], cwd=REPO,
                       check=True, capture_output=True, timeout=300)
        print("[site] figures regenerated from results/")
    dst = os.path.join(DOCS, "assets", "figures")
    os.makedirs(dst, exist_ok=True)
    for name in os.listdir(os.path.join(REPO, "paper", "figures")):
        if name.endswith((".png", ".pdf")):
            shutil.copy(os.path.join(REPO, "paper", "figures", name), dst)
    shutil.copy(os.path.join(REPO, "AdaptiShield_Architecture_v3.drawio.png"),
                os.path.join(dst, "implementation_architecture.png"))


# ── manuscript ───────────────────────────────────────────────────────────
def _slug(heading):
    s = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
    return s[:60]


def manuscript():
    """paper/manuscript.md as ONE page — a paper scrolls; it does not paginate.

    Sections become anchors, the right-hand table of contents gives navigation,
    and a contents list at the top jumps within the page. The disclaimer appears
    once, at the top, where a reader arriving from anywhere will pass it.
    """
    src = open(os.path.join(REPO, "paper", "manuscript.md")).read()
    src = src.replace("](figures/", "](../assets/figures/")
    src = src.replace("](../AdaptiShield_Architecture_v3.drawio.png)",
                      "](../assets/figures/implementation_architecture.png)")

    parts = re.split(r"^(## .+)$", src, flags=re.M)
    front, sections = parts[0], list(zip(parts[1::2], parts[2::2]))

    # Title block: the H1 and the author lines, centred like a paper's.
    lines = front.strip().split("\n")
    title = lines[0].lstrip("# ").strip()
    rest = "\n".join(lines[1:]).strip()
    abstract_at = rest.find("**Abstract**")
    byline, abstract = (rest[:abstract_at].strip(), rest[abstract_at:].strip()) \
        if abstract_at >= 0 else (rest, "")

    contents = "\n".join(
        f"- [{h[3:].strip()}](#{_slug(h[3:].strip())})" for h, _ in sections)

    body = "".join(
        f'\n\n<a id="{_slug(h[3:].strip())}"></a>\n\n{h}{b}' for h, b in sections)

    page = f"""{GEN_MARK}---
title: Manuscript
hide: [navigation]
---

{DISCLAIMER}
<div class="paper-title" markdown>

# {title}

{byline}

</div>

{abstract}

<div class="paper-contents" markdown>

**Contents**

{contents}

</div>

[:material-file-word: Download the Word draft](https://github.com/ahmadkhanraj01/adaptishield/raw/main/paper/AdaptiShield-Manuscript.docx){{ .md-button }}
[:material-github: Source markdown](https://github.com/ahmadkhanraj01/adaptishield/blob/main/paper/manuscript.md){{ .md-button }}

---
{body}

<style>
.paper-title{{text-align:center;margin:1rem 0 1.5rem}}
.paper-title h1{{margin-bottom:.6rem}}
.paper-contents{{columns:2;column-gap:2rem;font-size:.85rem;margin:1rem 0}}
.paper-contents ul{{margin:0}}
@media (max-width:700px){{.paper-contents{{columns:1}}}}
.md-typeset h2{{margin-top:2.6rem}}
</style>
"""
    out = os.path.join(DOCS, "manuscript")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    with open(os.path.join(out, "index.md"), "w") as fh:
        fh.write(page)
    print(f"[site] manuscript: one page, {len(sections)} sections")
    return [("Manuscript", "manuscript/index.md")]


# ── numbers, from results/ only ──────────────────────────────────────────
def numbers():
    camp = _load("results/campaign/campaign.json")["summary"]
    nf = _load("results/noise_floor/agentdojo_benign.json")["summary"]
    tr = _load("results/phase16_model_transfer/transfer.json")
    inc, cand = tr["models"]["incumbent"], tr["models"]["candidate"]

    def pct(x): return f"{100*x:.1f}%"
    def ci(r): return f"[{100*r['ci_low']:.1f}%, {100*r['ci_high']:.1f}%]"

    det, ext = camp["detection"], camp["benign"]["fpr_external"]
    t_inc, t_cand = tr["per_model"][inc], tr["per_model"][cand]
    return {
        "detection": (f"{det['hits']}/{det['n']} = {pct(det['rate'])}", ci(det), "results/campaign/"),
        "fpr": (f"{ext['hits']}/{ext['n']} = {pct(ext['rate'])}", ci(ext) + f" · stable over {nf['n_runs']} recordings", "results/noise_floor/"),
        # ⚠ transfer.json is ONE recording per model — its own `repeats` field says
        # so, and says no run-to-run spread may be quoted from it. The label has to
        # carry that: the paper's headline for the incumbent's no-target stratum is
        # 10.0%, the median of three recordings in results/noise_floor/, and a tile
        # reading 13.3% without "run 0" on it looks like the paper contradicting
        # the site.
        "strat_inc": (f"{pct(t_inc['IA-target']['rate'])} vs {pct(t_inc['IA-notarget']['rate'])}", f"{inc} · run 0 · gap {100*tr['gap'][inc]:.1f} pts", "results/phase16_model_transfer/"),
        "strat_cand": (f"{pct(t_cand['IA-target']['rate'])} vs {pct(t_cand['IA-notarget']['rate'])}", f"{cand} · run 0 · gap {100*tr['gap'][cand]:.1f} pts", "results/phase16_model_transfer/"),
        "misses": (", ".join(camp["misses"]), "every one address-free", "results/campaign/"),
    }


def external():
    """Published attack-success figures we position against — verbatim rows only.

    Two gates, both deliberate. `verified` must be "verbatim", so a row that no
    human has read out of its primary source cannot reach the site any more than
    it can reach the manuscript. And only the attack-success family is shown:
    PIShield's table is FPR/FNR, a different axis, and mixing the two under one
    "Reported" column would put a detector's false-positive rate beside a
    defence's ASR as though they were comparable.
    """
    with open(os.path.join(REPO, "paper", "external_numbers.json")) as fh:
        data = json.load(fh)
    out = []
    for src in data["sources"]:
        for row in src["rows"]:
            metric = row.get("metric", "")
            if row.get("verified") != "verbatim":
                continue
            if "attack success" not in metric and "ASR" not in metric:
                continue
            value = row.get("display") or f"{row['value_pct']}%"
            out.append((row["system"], row.get("setting", "—"), metric, value,
                        src["citation"].split(",")[0], src["url"]))
    return out


