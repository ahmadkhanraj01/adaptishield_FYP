def writeup():
    """writeup/**.md copied page-for-page, figure paths pointed at the shared
    assets, internal links kept internal, repo links sent to GitHub."""
    src_dir = os.path.join(REPO, "writeup")
    out = os.path.join(DOCS, "writeup")
    shutil.rmtree(out, ignore_errors=True)
    internal = {rel for rel, _ in WRITEUP_PAGES}
    nav = []
    for rel, title in WRITEUP_PAGES:
        md = open(os.path.join(src_dir, rel)).read()
        depth = rel.count("/")
        up = "../" * (depth + 1)
        md = md.replace("figures/fig5_implementation_diagram.png",
                        "figures/implementation_architecture.png")
        md = re.sub(r"\]\(figures/([^)]+\.png)\)", rf"]({up}assets/figures/\1)", md)

        def link(m):
            target, frag = m.group(1), m.group(2) or ""
            if target in internal:
                # keep relative to this page's own directory
                if depth and not target.startswith("rules/"):
                    return f"]({'../' * depth}{target}{frag})"
                if not depth and target.startswith("rules/"):
                    return f"]({target}{frag})"
                if depth and target.startswith("rules/"):
                    return f"]({target[len('rules/'):]}{frag})"
                return f"]({target}{frag})"
            return f"]({GITHUB}{target}{frag})"
        md = re.sub(r"\]\(((?!https?://|#|\.\./|assets/)[^)]+\.(?:md|py|json|txt|yaml|yml|html))(#[^)]*)?\)",
                    link, md)
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w") as fh:
            fh.write(GEN_MARK + WRITEUP_NOTE + md)
        nav.append(f"    - \"{title}\": writeup/{rel}")
    print(f"[site] write-up: {len(nav)} pages from writeup/")
    return "\n".join(nav)


STATUS = [  # (marker, css class, label) — status is icon + label, never colour alone
    ("⛔", "withdrawn", "withdrawn"),
    ("🔴", "open", "open defect"),
    ("🔲", "next", "planned"),
    ("🟡", "partial", "partial"),
    ("🔵", "blocked", "blocked"),
    ("✅", "done", "done"),
]


def _status(cell):
    for marker, cls, label in STATUS:
        if marker in cell:
            return marker, cls, label
    return "·", "unknown", "unknown"


def _phase_rows(md):
    """Rows of Phase.md's Snapshot table: (id, scope, state-cell)."""
    rows = []
    for line in md.split("\n"):
        m = re.match(r"^\|\s*\**([0-9]+[a-z]?)\**\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$", line)
        if m:
            rows.append(m.groups())
    return rows


def _strip_md(s):
    return re.sub(r"[*_`]|\(§[^)]*\)", "", s).strip()


def progress():
    src = _repo_links(open(os.path.join(REPO, "Phase.md")).read())
    rows = _phase_rows(src)

    # Anchor every "### N · …" section so the board can deep-link into it.
    def anchor(m):
        return f'<a id="phase-{m.group(1).lower()}"></a>\n{m.group(0)}'
    src = re.sub(r"^### ([0-9]+[a-z]?) · .+$", anchor, src, flags=re.M)
    section_ids = set(re.findall(r'id="phase-([0-9a-z]+)"', src))

    counts = {}
    cards = []
    for pid, scope, state in rows:
        marker, cls, label = _status(state)
        counts[label] = counts.get(label, 0) + 1
        short = _strip_md(state)
        short = (short[:90] + "…") if len(short) > 90 else short
        href = f"#phase-{pid.lower()}" if pid.lower() in section_ids else "#snapshot"
        cards.append(
            f'<a class="ph {cls}" href="{href}">'
            f'<span class="id">{pid}</span>'
            f'<span class="st">{marker} {label}</span>'
            f'<span class="sc">{_strip_md(scope)}</span>'
            f'<span class="dt">{short}</span></a>')

    stats = "".join(
        f'<div class="stat"><b>{counts.get(l, 0)}</b><span>{m} {l}</span></div>'
        for m, _, l in STATUS if counts.get(l))

