"""
Build the site's generated pages from the repository's own sources.

THE ONE RULE. The review deck was hand-written, so it drifted until it
contradicted the repository in five places on the day two hardening items
closed. This site is the opposite: nothing here is a second copy of anything.
The manuscript is split from paper/manuscript.md, the figures are regenerated
from results/, and every number on the home page is read from a results/*.json
at build time. If a number is not in a tracked artifact it does not appear —
which is Rules.md §7 applied to a website.

    python3 site_src/build.py      # writes site_src/docs/** (generated parts)
    mkdocs build                   # renders site/
"""
